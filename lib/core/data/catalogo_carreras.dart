import 'package:flutter/material.dart';

/// Un curso predeterminado del catálogo: sirve de plantilla para el
/// formulario de curso (código, nombre, créditos, descripción y carrera).
class CursoCatalogo {
  final String codigo;
  final String nombre;
  final int creditos;
  final int ciclo;
  final String descripcion;

  const CursoCatalogo({
    required this.codigo,
    required this.nombre,
    required this.creditos,
    required this.ciclo,
    required this.descripcion,
  });
}

/// Una carrera universitaria con sus cursos predeterminados.
class CarreraCatalogo {
  final String nombre;
  final String sigla;
  final IconData icono;
  final Color color;
  final List<CursoCatalogo> cursos;

  const CarreraCatalogo({
    required this.nombre,
    required this.sigla,
    required this.icono,
    required this.color,
    required this.cursos,
  });

  int get totalCreditos => cursos.fold(0, (suma, c) => suma + c.creditos);
}

/// Carrera del catálogo con ese [nombre], o null si no está en el catálogo.
CarreraCatalogo? carreraPorNombre(String? nombre) {
  if (nombre == null) return null;
  for (final carrera in catalogoCarreras) {
    if (carrera.nombre == nombre) return carrera;
  }
  return null;
}

